package com.now.nowbot.model.maimai

import com.fasterxml.jackson.annotation.JsonProperty

// 外号
data class MaiAlias(
    @field:JsonProperty("song_id") var songID: Int = 0,
    @field:JsonProperty("aliases") var alias: List<String> = mutableListOf(),
) {
    /**
     * 原地去掉含有 emoji 的别名，并返回自身方便链式调用。
     *
     * 舞萌外号库里有「🐴」「🦍」「=⚡」「开🦌」这类带 emoji 的别名：
     * 它们不适合参与外号搜索，而且因为更短，还可能被 `minByOrNull { it.length }`
     * 选成展示用的首选别名，所以统一在读取外号时剔除。
     * 只有纯文本（含 ★、☆、→、⑨、△ 这类普通符号）的别名不受影响。
     */
    fun withoutEmojiAliases(): MaiAlias {
        // 绝大多数歌都没有 emoji 外号，先短路，避免每次都分配新列表
        if (alias.none { it.containsEmoji() }) return this

        alias = alias.filterNot { it.containsEmoji() }
        return this
    }
}

/**
 * 是否含有 emoji。按 Unicode 的 Extended_Pictographic + Emoji_Presentation 判定，
 * 因此 ♥、♂、© 这类默认文本展示的 emoji 也算，而 ★、☆、♪、→ 不算。
 */
private fun String.containsEmoji(): Boolean {
    val codePoints = codePoints().iterator()
    while (codePoints.hasNext()) {
        if (codePoints.nextInt().isEmojiCodePoint()) return true
    }
    return false
}

private fun Int.isEmojiCodePoint(): Boolean {
    // 补充平面：表情、旗帜、肤色等 emoji 都在 1F000..1FAFF
    if (this in 0x1F000..0x1FAFF) return true

    return this in BMP_EMOJI_POINTS.first()..BMP_EMOJI_POINTS.last()
            && this in BMP_EMOJI_POINTS
}

